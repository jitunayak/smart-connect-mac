// smartconnect-mac-helper: the small native pieces the Rust daemon cannot do from a CLI on
// macOS. Every command is intentionally self-contained and prints JSON lines where the daemon
// needs to react to events.
//
//   pasteboard-watch           watch NSPasteboard, print {"text":...,"concealed":bool} per change
//   pasteboard-copy            read stdin and put it on NSPasteboard
//   lock-screen                lock the session (SACLockScreenImmediate, AppleScript fallback)
//   session-locked             print 1 while the screen is locked, else 0
//   session-locked-wait        stream 1/0 lines on lock and unlock (distributed notifications)
//   ble-advertise --device-id  advertise the ReadyFor GATT service as a peripheral
//   ble-wake --frame B64 --ids JSON
//                              scan for a paired phone, connect and write the invite
//   ble-watch-power            print {"event":"poweredOn"} whenever Bluetooth turns on
//   camera-feed --width W --height H [--device-uid UID]
//                              raw BGRA frames on stdin → the camera extension's sink stream
//                              (default: OBS Virtual Camera), so every app sees the phone camera
//
// Build with -Xlinker -sectcreate __TEXT __info_plist HelperInfo.plist so CoreBluetooth has the
// usage description macOS requires.

