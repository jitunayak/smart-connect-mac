// MARK: - JSON output

func emit(_ object: [String: Any]) {
    guard let data = try? JSONSerialization.data(withJSONObject: object, options: [.sortedKeys]),
          let line = String(data: data, encoding: .utf8) else { return }
    print(line)
    fflush(stdout)
}

func fail(_ message: String, code: Int32 = 1) -> Never {
    FileHandle.standardError.write((message + "\n").data(using: .utf8)!)
    exit(code)
}

// MARK: - Pasteboard

func pasteboardWatch() -> Never {
    let pb = NSPasteboard.general
    var last = pb.changeCount
    let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]
    while true {
        if pb.changeCount != last {
            last = pb.changeCount
            let types = Set((pb.types ?? []).map(\.rawValue))
            let concealed = !types.isDisjoint(with: concealedTypes)
            let text = pb.string(forType: .string) ?? ""
            if !text.isEmpty {
                emit(["text": text, "concealed": concealed])
            }
        }
        Thread.sleep(forTimeInterval: 0.35)
    }
}

func pasteboardCopy() -> Never {
    let data = FileHandle.standardInput.readDataToEndOfFile()
    guard let text = String(data: data, encoding: .utf8) else { fail("stdin is not UTF-8") }
    let pb = NSPasteboard.general
    pb.clearContents()
    pb.setString(text, forType: .string)
    exit(0)
}

// MARK: - Lock screen

typealias SACLockScreenImmediateFn = @convention(c) () -> Int32

func lockScreen() -> Never {
    if let handle = dlopen("/System/Library/PrivateFrameworks/login.framework/login", RTLD_NOW),
       let sym = dlsym(handle, "SACLockScreenImmediate") {
        let fn = unsafeBitCast(sym, to: SACLockScreenImmediateFn.self)
        if fn() == 0 { exit(0) }
    }
    // Fallback: the standard Lock Screen keystroke. Requires Accessibility permission.
    let p = Process()
    p.executableURL = URL(fileURLWithPath: "/usr/bin/osascript")
    p.arguments = ["-e", "tell application \"System Events\" to keystroke \"q\" using {control down, command down}"]
    do {
        try p.run()
        p.waitUntilExit()
        exit(p.terminationStatus)
    } catch {
        fail("lock-screen failed: \(error.localizedDescription)")
    }
}

func sessionLocked() -> Never {
    if let dict = CGSessionCopyCurrentDictionary() as? [String: Any] {
        let locked = (dict["CGSSessionScreenIsLocked"] as? Bool) ?? (dict["CGSSessionScreenIsLocked"] as? Int == 1)
        print(locked ? "1" : "0")
    } else {
        print("0")
    }
    exit(0)
}

/// Streams lock state changes as 1/0 lines and never exits. On this macOS the session dictionary
/// no longer carries a locked key, and the daemon polls it for the phone's "Lock PC" tile; the
/// distributed notifications fire correctly on lock and unlock, so they are the source of truth.
func sessionLockedWait() -> Never {
    let report: (Notification) -> Void = { note in
        let locked = note.name.rawValue == "com.apple.screenIsLocked"
        print(locked ? "1" : "0")
        fflush(stdout)
    }
    DistributedNotificationCenter.default().addObserver(
        forName: NSNotification.Name("com.apple.screenIsLocked"),
        object: nil, queue: nil, using: report)
    DistributedNotificationCenter.default().addObserver(
        forName: NSNotification.Name("com.apple.screenIsUnlocked"),
        object: nil, queue: nil, using: report)
    dispatchMain()
}

// MARK: - Bluetooth

let serviceUUID = CBUUID(string: "00005246-0000-1000-8000-00805F9B34FB")
let chrInvite = CBUUID(string: "00000722-0000-1000-8000-00805F9B34FB")
let chrNotify = CBUUID(string: "00000726-0000-1000-8000-00805F9B34FB")
let chrWriteNotify = CBUUID(string: "00000728-0000-1000-8000-00805F9B34FB")
let chrCompanion = CBUUID(string: "00005247-0000-1000-8000-00805F9B34FB")

final class Advertiser: NSObject, CBPeripheralManagerDelegate {
    private var manager: CBPeripheralManager!
    private let deviceID: String
    private var started = false

    init(deviceID: String) {
        self.deviceID = deviceID
        super.init()
        manager = CBPeripheralManager(delegate: self, queue: .main)
        // Never exit: the daemon keeps this process alive and kills it on shutdown.
        RunLoop.main.run()
    }

    func peripheralManagerDidUpdateState(_ peripheral: CBPeripheralManager) {
        switch peripheral.state {
        case .poweredOn:
            let chars = [
                CBMutableCharacteristic(type: chrInvite, properties: [.write, .writeWithoutResponse], value: nil, permissions: [.writeable]),
                CBMutableCharacteristic(type: chrNotify, properties: [.write, .writeWithoutResponse], value: nil, permissions: [.writeable]),
                CBMutableCharacteristic(type: chrWriteNotify, properties: [.write, .writeWithoutResponse, .notify], value: nil, permissions: [.writeable]),
                CBMutableCharacteristic(type: chrCompanion, properties: [.notify], value: nil, permissions: []),
            ]
            let service = CBMutableService(type: serviceUUID, primary: true)
            service.characteristics = chars
            peripheral.add(service)
        case .unauthorized:
            fail("Bluetooth permission denied (grant SmartConnect Bluetooth access in System Settings)")
        case .unsupported:
            fail("this Mac has no Bluetooth LE support")
        case .poweredOff:
            emit(["event": "poweredOff"])
        default:
            break
        }
    }

    func peripheralManager(_ peripheral: CBPeripheralManager, didAdd service: CBService, error: Error?) {
        if let error { fail("adding GATT service: \(error.localizedDescription)") }
        peripheral.startAdvertising([
            CBAdvertisementDataServiceUUIDsKey: [serviceUUID],
            CBAdvertisementDataLocalNameKey: "SmartConnect",
        ])
        emit(["event": "advertising", "deviceId": deviceID])
    }

    func peripheralManager(_ peripheral: CBPeripheralManager, didReceiveWrite requests: [CBATTRequest]) {
        for request in requests {
            let data = request.value ?? Data()
            emit(["event": "write", "characteristic": request.characteristic.uuid.uuidString, "bytes": data.count])
            peripheral.respond(to: request, withResult: .success)
        }
    }

    func peripheralManager(_ peripheral: CBPeripheralManager, didReceiveRead request: CBATTRequest) {
        peripheral.respond(to: request, withResult: .success)
    }
}

func bleAdvertise(deviceID: String) -> Never {
    _ = Advertiser(deviceID: deviceID)
    exit(0)
}

final class Waker: NSObject, CBCentralManagerDelegate, CBPeripheralDelegate {
    private var manager: CBCentralManager!
    private let frame: Data
    private let ids: [Data]
    private var peripheral: CBPeripheral?
    private var inviteCharacteristic: CBCharacteristic?
    private var wrote = false
    private let deadline: Date
    private var timer: Timer?

    init(frame: Data, ids: [Data], timeout: TimeInterval) {
        self.frame = frame
        self.ids = ids
        self.deadline = Date().addingTimeInterval(timeout)
        super.init()
        manager = CBCentralManager(delegate: self, queue: .main)
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            guard let self, Date() > self.deadline else { return }
            emit(["event": "error", "message": "phone not found over Bluetooth before the timeout"])
            exit(2)
        }
        RunLoop.main.run()
    }

    func centralManagerDidUpdateState(_ central: CBCentralManager) {
        switch central.state {
        case .poweredOn:
            emit(["event": "scanning"])
            central.scanForPeripherals(withServices: [serviceUUID], options: [CBCentralManagerScanOptionAllowDuplicatesKey: true])
        case .poweredOff:
            emit(["event": "error", "message": "Bluetooth is off on this computer"])
            exit(3)
        case .unauthorized:
            emit(["event": "error", "message": "Bluetooth permission denied for SmartConnect"])
            exit(4)
        case .unsupported:
            emit(["event": "error", "message": "this Mac has no Bluetooth LE support"])
            exit(5)
        default:
            break
        }
    }

    func centralManager(_ central: CBCentralManager,
                        didDiscover peripheral: CBPeripheral,
                        advertisementData: [String: Any],
                        rssi RSSI: NSNumber) {
        guard let serviceData = advertisementData[CBAdvertisementDataServiceDataKey] as? [CBUUID: Data],
              let payload = serviceData[serviceUUID],
              payload.count >= 16 else { return }
        let nonce = payload.suffix(16)
        let salt = nonce.prefix(8)
        for realID in ids {
            var material = Data(realID)
            material.append(salt)
            let digest = SHA256.hash(data: material)
            let candidate = Data(salt) + Data(digest.prefix(8))
            if candidate == nonce {
                emit(["event": "found", "name": peripheral.name ?? "", "rssi": RSSI.intValue])
                central.stopScan()
                self.peripheral = peripheral
                peripheral.delegate = self
                central.connect(peripheral, options: nil)
                return
            }
        }
    }

    func centralManager(_ central: CBCentralManager, didConnect peripheral: CBPeripheral) {
        peripheral.discoverServices([serviceUUID])
    }

    func centralManager(_ central: CBCentralManager, didFailToConnect peripheral: CBPeripheral, error: Error?) {
        emit(["event": "error", "message": "Bluetooth connect failed: \(error?.localizedDescription ?? "unknown")"])
        exit(6)
    }

    func peripheral(_ peripheral: CBPeripheral, didDiscoverServices error: Error?) {
        if let error {
            emit(["event": "error", "message": "discovering GATT services: \(error.localizedDescription)"])
            exit(7)
        }
        guard let service = peripheral.services?.first(where: { $0.uuid == serviceUUID }) else {
            emit(["event": "error", "message": "the phone has no ReadyFor service"])
            exit(8)
        }
        peripheral.discoverCharacteristics([chrInvite, chrNotify], for: service)
    }

    func peripheral(_ peripheral: CBPeripheral, didDiscoverCharacteristicsFor service: CBService, error: Error?) {
        if let error {
            emit(["event": "error", "message": "discovering GATT characteristics: \(error.localizedDescription)"])
            exit(9)
        }
        for ch in service.characteristics ?? [] {
            if ch.uuid == chrInvite {
                inviteCharacteristic = ch
                peripheral.setNotifyValue(true, for: ch)
            } else if ch.uuid == chrNotify {
                peripheral.setNotifyValue(true, for: ch)
            }
        }
        guard let ch = inviteCharacteristic else {
            emit(["event": "error", "message": "characteristic 0x0722 is missing"])
            exit(10)
        }
        peripheral.writeValue(frame, for: ch, type: .withResponse)
    }

    func peripheral(_ peripheral: CBPeripheral, didWriteValueFor characteristic: CBCharacteristic, error: Error?) {
        if let error {
            emit(["event": "error", "message": "writing the invite: \(error.localizedDescription)"])
            exit(11)
        }
        wrote = true
        emit(["event": "written", "bytes": frame.count])
        manager.cancelPeripheralConnection(peripheral)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) { exit(0) }
    }
}

func bleWake(frameBase64: String, idsJSON: String, timeout: TimeInterval) -> Never {
    guard let frame = Data(base64Encoded: frameBase64) else { fail("--frame is not base64") }
    guard let list = try? JSONSerialization.jsonObject(with: Data(idsJSON.utf8)) as? [String] else {
        fail("--ids is not a JSON string array")
    }
    let ids = list.compactMap { Data(base64Encoded: $0) }
    guard !ids.isEmpty else { fail("--ids has no decodable device ids") }
    _ = Waker(frame: frame, ids: ids, timeout: timeout)
    exit(0)
}

final class PowerWatcher: NSObject, CBCentralManagerDelegate {
    private var manager: CBCentralManager!
    override init() {
        super.init()
        manager = CBCentralManager(delegate: self, queue: .main)
        RunLoop.main.run()
    }
    func centralManagerDidUpdateState(_ central: CBCentralManager) {
        switch central.state {
        case .poweredOn: emit(["event": "poweredOn"])
        case .poweredOff: emit(["event": "poweredOff"])
        default: break
        }
    }
}

func bleWatchPower() -> Never {
    _ = PowerWatcher()
    exit(0)
}

// MARK: - Camera feed (phone webcam → a CoreMediaIO camera extension's sink stream)

/// The OBS Virtual Camera extension's device id (OBS's `mac-virtualcam` plug-in, key
/// `OBSCameraDeviceUUID`). Used when OBS.app isn't where we look for it.
let obsCameraDeviceUUID = "7626645E-4425-469E-9D8B-97E0FA59AC75"

func cmioProperty<T>(_ object: CMIOObjectID, _ selector: Int, _ type: T.Type) -> [T] {
    var address = CMIOObjectPropertyAddress(
        mSelector: CMIOObjectPropertySelector(selector),
        mScope: CMIOObjectPropertyScope(kCMIOObjectPropertyScopeGlobal),
        mElement: CMIOObjectPropertyElement(kCMIOObjectPropertyElementMain))
    var size: UInt32 = 0
    guard CMIOObjectGetPropertyDataSize(object, &address, 0, nil, &size) == noErr, size > 0 else { return [] }
    let count = Int(size) / MemoryLayout<T>.stride
    let buffer = UnsafeMutableRawPointer.allocate(byteCount: Int(size), alignment: MemoryLayout<T>.alignment)
    defer { buffer.deallocate() }
    var used: UInt32 = 0
    guard CMIOObjectGetPropertyData(object, &address, 0, nil, size, &used, buffer) == noErr else { return [] }
    return (0..<count).map { buffer.load(fromByteOffset: $0 * MemoryLayout<T>.stride, as: T.self) }
}

func cmioDeviceUID(_ device: CMIOObjectID) -> String? {
    var address = CMIOObjectPropertyAddress(
        mSelector: CMIOObjectPropertySelector(kCMIODevicePropertyDeviceUID),
        mScope: CMIOObjectPropertyScope(kCMIOObjectPropertyScopeGlobal),
        mElement: CMIOObjectPropertyElement(kCMIOObjectPropertyElementMain))
    var uid: Unmanaged<CFString>?
    var used: UInt32 = 0
    let size = UInt32(MemoryLayout<Unmanaged<CFString>?>.size)
    guard CMIOObjectGetPropertyData(device, &address, 0, nil, size, &used, &uid) == noErr else { return nil }
    return uid?.takeRetainedValue() as String?
}

/// `camera-feed --width W --height H [--device-uid UID]`: reads raw BGRA frames (W*H*4 bytes
/// each) from stdin and enqueues them on the camera extension's sink stream, so every app that
/// opens that camera sees the phone. Prints {"event":"ready"} once the sink runs; exits when
/// stdin closes. Allowing the queue to be filled needs the Camera permission (TCC).
func cameraFeed(width: Int, height: Int, deviceUID: String) -> Never {
    // Let CoreMediaIO see camera-extension devices from this process.
    var allow: UInt32 = 1
    var allowAddress = CMIOObjectPropertyAddress(
        mSelector: CMIOObjectPropertySelector(kCMIOHardwarePropertyAllowScreenCaptureDevices),
        mScope: CMIOObjectPropertyScope(kCMIOObjectPropertyScopeGlobal),
        mElement: CMIOObjectPropertyElement(kCMIOObjectPropertyElementMain))
    CMIOObjectSetPropertyData(CMIOObjectID(kCMIOObjectSystemObject), &allowAddress, 0, nil,
                              UInt32(MemoryLayout<UInt32>.size), &allow)

    let wanted = deviceUID.uppercased()
    var device: CMIOObjectID?
    let deadline = Date().addingTimeInterval(5)
    while device == nil && Date() < deadline {
        device = cmioProperty(CMIOObjectID(kCMIOObjectSystemObject), kCMIOHardwarePropertyDevices, CMIOObjectID.self)
            .first { cmioDeviceUID($0)?.uppercased() == wanted }
        if device == nil { RunLoop.current.run(until: Date().addingTimeInterval(0.2)) }
    }
    guard let device else {
        fail("camera-feed: camera \(deviceUID) not found (is OBS installed and its virtual camera enabled once?)")
    }
    // The extension's streams: [source, sink]; frames go to the sink.
    let streams = cmioProperty(device, kCMIODevicePropertyStreams, CMIOStreamID.self)
    guard streams.count >= 2 else { fail("camera-feed: the camera has no sink stream") }
    let sink = streams[1]

    var queueRef: Unmanaged<CMSimpleQueue>?
    let status = CMIOStreamCopyBufferQueue(sink, { _, _, _ in }, nil, &queueRef)
    guard status == noErr, let queue = queueRef?.takeRetainedValue() else {
        fail("camera-feed: can't open the sink queue (\(status)); allow Camera access for Smart Connect")
    }
    let started = CMIODeviceStartStream(device, sink)
    guard started == noErr else { fail("camera-feed: can't start the sink stream (\(started))") }

    var format: CMVideoFormatDescription?
    CMVideoFormatDescriptionCreate(allocator: kCFAllocatorDefault, codecType: kCVPixelFormatType_32BGRA,
                                   width: Int32(width), height: Int32(height), extensions: nil,
                                   formatDescriptionOut: &format)
    let attributes: NSDictionary = [
        kCVPixelBufferWidthKey: width,
        kCVPixelBufferHeightKey: height,
        kCVPixelBufferPixelFormatTypeKey: kCVPixelFormatType_32BGRA,
        kCVPixelBufferIOSurfacePropertiesKey: [CFString: CFTypeRef](),
    ]
    var pool: CVPixelBufferPool?
    CVPixelBufferPoolCreate(kCFAllocatorDefault, nil, attributes, &pool)
    guard let format, let pool else { fail("camera-feed: can't create the pixel buffer pool") }

    signal(SIGPIPE, SIG_IGN)
    emit(["event": "ready", "width": width, "height": height])
    let frameBytes = width * height * 4
    let frame = UnsafeMutablePointer<UInt8>.allocate(capacity: frameBytes)
    defer { frame.deallocate() }
    let input = FileHandle.standardInput.fileDescriptor
    while true {
        var got = 0
        while got < frameBytes {
            let n = read(input, frame + got, frameBytes - got)
            if n <= 0 {
                CMIODeviceStopStream(device, sink)
                exit(0)
            }
            got += n
        }
        // Drop the frame when the extension is behind instead of growing a backlog.
        if CMSimpleQueueGetCount(queue) >= CMSimpleQueueGetCapacity(queue) { continue }
        var pixelBuffer: CVPixelBuffer?
        guard CVPixelBufferPoolCreatePixelBuffer(kCFAllocatorDefault, pool, &pixelBuffer) == kCVReturnSuccess,
              let pixelBuffer else { continue }
        CVPixelBufferLockBaseAddress(pixelBuffer, [])
        let dst = CVPixelBufferGetBaseAddress(pixelBuffer)!.assumingMemoryBound(to: UInt8.self)
        let dstRow = CVPixelBufferGetBytesPerRow(pixelBuffer)
        let srcRow = width * 4
        for row in 0..<height {
            memcpy(dst + row * dstRow, frame + row * srcRow, srcRow)
        }
        CVPixelBufferUnlockBaseAddress(pixelBuffer, [])
        var timing = CMSampleTimingInfo(duration: CMTime(value: 1, timescale: 30),
                                        presentationTimeStamp: CMClockGetTime(CMClockGetHostTimeClock()),
                                        decodeTimeStamp: .invalid)
        var sample: CMSampleBuffer?
        CMSampleBufferCreateForImageBuffer(allocator: kCFAllocatorDefault, imageBuffer: pixelBuffer,
                                           dataReady: true, makeDataReadyCallback: nil, refcon: nil,
                                           formatDescription: format, sampleTiming: &timing,
                                           sampleBufferOut: &sample)
        if let sample {
            // The queue takes over this retain; the extension releases the buffer.
            CMSimpleQueueEnqueue(queue, element: Unmanaged.passRetained(sample).toOpaque())
        }
    }
}

// MARK: - Entry point

let args = Array(CommandLine.arguments.dropFirst())
guard let command = args.first else {
    fail("usage: smartconnect-mac-helper <pasteboard-watch|pasteboard-copy|lock-screen|session-locked|session-locked-wait|ble-advertise|ble-wake|ble-watch-power|camera-feed>")
}

func option(_ name: String) -> String? {
    guard let i = args.firstIndex(of: name), i + 1 < args.count else { return nil }
    return args[i + 1]
}

switch command {
case "pasteboard-watch": pasteboardWatch()
case "pasteboard-copy": pasteboardCopy()
case "lock-screen": lockScreen()
case "session-locked": sessionLocked()
case "session-locked-wait": sessionLockedWait()
case "ble-advertise":
    guard let deviceID = option("--device-id") else { fail("ble-advertise needs --device-id") }
    bleAdvertise(deviceID: deviceID)
case "ble-wake":
    guard let frame = option("--frame"), let ids = option("--ids") else { fail("ble-wake needs --frame and --ids") }
    let timeout = TimeInterval(option("--timeout") ?? "35") ?? 35
    bleWake(frameBase64: frame, idsJSON: ids, timeout: timeout)
case "ble-watch-power": bleWatchPower()
case "camera-feed":
    let width = Int(option("--width") ?? "1920") ?? 1920
    let height = Int(option("--height") ?? "1080") ?? 1080
    cameraFeed(width: width, height: height, deviceUID: option("--device-uid") ?? obsCameraDeviceUUID)
default: fail("unknown command \(command)")
}
